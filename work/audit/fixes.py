def del_step(tid, sub, ref=''):
    t = T(tid)
    for p in t['parts']:
        for s in list(p['steps']):
            if sub in s.get('text', ''):
                if s.get('imgs'):
                    raise FixError('%s: 画像付きの手順は消さない(先に画像を移す)' % tid)
                p['steps'].remove(s)
                log(tid, '手順を削除:「%s」' % s['text'], ref)
                return
    raise FixError('%s: 手順「%s」なし' % (tid, sub))

